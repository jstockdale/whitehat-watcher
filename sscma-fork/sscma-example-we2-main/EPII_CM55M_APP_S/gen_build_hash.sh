#!/bin/bash
# Generates WATCHER_BUILD_HASH from the key source files.
# Run before every Himax build to ensure the fingerprint is unique per build.
# John (2026-10-08): "The build fingerprint is supposed to be a hash of the
# build itself. If that string is stale we need to assume the build is stale."

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
HASH_HEADER="$SCRIPT_DIR/library/sscma_micro/sscma/server/at/callback/watcher_build_hash.h"

# Key source files that define the firmware behavior
KEY_SOURCES=(
    "$SCRIPT_DIR/library/sscma_micro_porting/porting/himax/we2/ma_transport_spi.cpp"
    "$SCRIPT_DIR/library/sscma_micro_porting/porting/himax/we2/ma_transport_spi.h"
    # v0.4.20.61: the camera file carries behavior-defining code too (crop
    # buffer management) — a change there must move the fingerprint.
    "$SCRIPT_DIR/library/sscma_micro_porting/porting/himax/we2/ma_camera_himax.cpp"
)

# Verify all key sources exist
for src in "${KEY_SOURCES[@]}"; do
    if [ ! -f "$src" ]; then
        echo "ERROR: Key source not found: $src" >&2
        exit 1
    fi
done

# Hash the concatenated sources
BUILD_HASH=$(cat "${KEY_SOURCES[@]}" | sha256sum | cut -d' ' -f1)
FINGERPRINT=${BUILD_HASH:0:16}

# Extract current FW_ID from the header (preserve it)
FW_ID=$(grep -o '#define WATCHER_FW_ID "[^"]*"' "$HASH_HEADER" | cut -d'"' -f2)

# Regenerate the header
cat > "$HASH_HEADER" <<EOF
#pragma once
/* Watcher firmware version identifier and build hash. Single source of
 * truth for the FW ID — included by both the AT server (resource.hpp) and
 * the porting layer (ma_camera_himax.cpp) which cannot include resource.hpp
 * due to AT-server dependencies. */
#define WATCHER_FW_ID "$FW_ID"
/* SHA256 of the key source files at build time. Printed at boot
 * in the DIAG line so the running firmware can be verified against
 * build artifacts. Generated by gen_build_hash.sh — DO NOT EDIT MANUALLY. */
#define WATCHER_BUILD_HASH "$BUILD_HASH"
EOF

echo "Build hash generated: $FINGERPRINT (full: $BUILD_HASH)"
echo "FW ID preserved: $FW_ID"

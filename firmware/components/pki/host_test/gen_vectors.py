#!/usr/bin/env python3
"""Generate C test vectors for components/pki/host_test/test_pki.c.

Imports the REAL canonical-bytes builders from
firmware/tools/bake_tier2_keys.py, signs with ephemeral keys via the
`cryptography` package, and emits vectors.h. Nothing secret leaves this
process; all keys are ephemeral.

The C host test then rebuilds the same bytes with pki_verify.c and
memcmps — proving the device-side canonicalization is byte-identical
to the Python (Lambda-side) implementation.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools"))
import bake_tier2_keys as bake

from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.ed25519 import \
    Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.utils import (
    Prehashed, decode_dss_signature)
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.serialization import (
    Encoding, PublicFormat)


def c_bytes(name, data):
    lines = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk))
    return ("static const uint8_t %s[%d] = {\n%s\n};"
            % (name, len(data), ",\n".join(lines)))


def c_str(name, s):
    return 'static const char %s[] =\n    "%s";' % (
        name, s.replace("\\", "\\\\").replace('"', '\\"'))


def main():
    # --- ephemeral Tier 1 (P-256) key for the provision vector ---
    t1 = ec.generate_private_key(ec.SECP256R1())
    nums = t1.public_key().public_numbers()
    pub65 = (b"\x04" + nums.x.to_bytes(32, "big")
             + nums.y.to_bytes(32, "big"))

    # --- ephemeral Tier 0 (Ed25519) key for the rotate vector ---
    t0 = Ed25519PrivateKey.generate()
    t0pub = t0.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)

    # --- provision command vector ---
    cmd = {
        "format": "watcher-provision-v1",
        "cmd": "install_commander_key",
        "device": "*",
        "nonce": "0123456789abcdef0123456789abcdef",
        "issued_at": "2026-09-27T00:00:00Z",
        "expires_at": "2026-09-27T00:15:00Z",
        "params": {"pubkey_hex": "ab" * 32},
    }
    canon = bake.provision_canonical_bytes(cmd)
    digest = hashlib.sha256(canon).digest()
    der = t1.sign(digest, ec.ECDSA(Prehashed(hashes.SHA256())))
    r, s = decode_dss_signature(der)
    raw64 = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    # sanity: the signature really verifies (proves the byte layout)
    t1.public_key().verify(der, digest,
                           ec.ECDSA(Prehashed(hashes.SHA256())))
    params_canon = json.dumps(cmd["params"], sort_keys=True,
                              separators=(",", ":"),
                              ensure_ascii=True)
    cmd_json = json.dumps(cmd, separators=(",", ":"))

    # --- canonical-JSON battery (input text -> expected canonical) ---
    json_cases = [
        '{"b":1,"a":2}',
        '{"z":{"d":4,"c":3},"a":[1,true,null,"x"]}',
        '{}',
        '{"s":"hello\\nworld\\t\\"q\\" \\\\ /"}',
        '{"u":"caf\\u00e9 \\u4e2d\\ud83d\\ude00"}',
        '{"ctrl":"\\u0001\\u001f\\u007f"}',
        '{"n":0}',
        '{"neg":-42}',
        '{"big":9007199254740991}',
        '{"arr":[]}',
        '{"nested":{"a":{"b":{"c":1}}}}',
        '{"k":"v","k2":"w"}',
    ]
    json_vec = []
    for text in json_cases:
        expected = json.dumps(json.loads(text), sort_keys=True,
                              separators=(",", ":"),
                              ensure_ascii=True)
        json_vec.append((text, expected))

    # --- rotate vector: must beat the baked test header's serial/expiry
    hdr = open(os.path.join(HERE, "..", "tier2_keys.h")).read()
    baked_serial = int(re.search(r"TIER1_CERT_SERIAL\s+(\d+)u",
                                 hdr).group(1))
    baked_exp = int(re.search(r"TIER1_CERT_EXPIRES_AT\s+(\d+)ull",
                              hdr).group(1))
    t1b = ec.generate_private_key(ec.SECP256R1())
    n2 = t1b.public_key().public_numbers()
    new_pub65 = (b"\x04" + n2.x.to_bytes(32, "big")
                 + n2.y.to_bytes(32, "big"))
    new_exp = baked_exp + 86400 * 30
    new_serial = baked_serial + 1
    import struct
    rotate_canon = (b"WATCHER-TIER1-ROTATE-v1" + new_pub65
                    + struct.pack(">Q", new_exp)
                    + struct.pack(">I", new_serial))
    rotate_sig = t0.sign(rotate_canon)
    # sanity
    t0.public_key().verify(rotate_sig, rotate_canon)

    out = []
    out.append("/* GENERATED by gen_vectors.py — do not edit. */")
    out.append("#pragma once")
    out.append(c_str("VEC_CMD_JSON", cmd_json))
    out.append(c_bytes("VEC_CANON", canon))
    out.append(c_bytes("VEC_SIG_RAW64", raw64))
    out.append(c_str("VEC_PARAMS_CANON", params_canon))
    out.append("#define VEC_JSON_NCASES %d" % len(json_vec))
    for i, (text, expected) in enumerate(json_vec):
        out.append(c_str("VEC_JSON_IN_%d" % i, text))
        out.append(c_str("VEC_JSON_EXP_%d" % i, expected))
    out.append(c_bytes("VEC_T0_PUB32", t0pub))
    out.append(c_bytes("VEC_ROTATE_CANON", rotate_canon))
    out.append(c_bytes("VEC_ROTATE_SIG64", rotate_sig))
    out.append(c_bytes("VEC_ROTATE_PUB65", new_pub65))
    out.append(c_str("VEC_ROTATE_TIER0_SIG_HEX", rotate_sig.hex()))
    out.append("#define VEC_ROTATE_EXP %dull" % new_exp)
    out.append("#define VEC_ROTATE_SERIAL %du" % new_serial)
    out.append("#define VEC_BAKED_SERIAL %du" % baked_serial)
    out.append("#define VEC_BAKED_EXP %dull" % baked_exp)

    # --- rotate_tier1 as a full provision command (Tier 1 outer sig +
    #     Tier 0 countersignature in params) ---
    import datetime
    new_exp_iso = (datetime.datetime(1970, 1, 1)
                   + datetime.timedelta(seconds=new_exp)
                   ).strftime("%Y-%m-%dT%H:%M:%SZ")
    rot_cmd = {
        "format": "watcher-provision-v1",
        "cmd": "rotate_tier1",
        "device": "*",
        "nonce": "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        "issued_at": "2026-09-27T00:00:00Z",
        "expires_at": "2026-09-27T00:15:00Z",
        "params": {
            "p256_pubkey_hex": new_pub65.hex(),
            "expires_at": new_exp_iso,
            "tier0_sig_hex": rotate_sig.hex(),
            "serial": new_serial,
        },
    }
    rot_canon = bake.provision_canonical_bytes(rot_cmd)
    rot_digest = hashlib.sha256(rot_canon).digest()
    rot_der = t1.sign(rot_digest, ec.ECDSA(Prehashed(hashes.SHA256())))
    rr, rs = decode_dss_signature(rot_der)
    rot_raw64 = rr.to_bytes(32, "big") + rs.to_bytes(32, "big")
    t1.public_key().verify(rot_der, rot_digest,
                           ec.ECDSA(Prehashed(hashes.SHA256())))
    out.append(c_str("VEC_ROTATE_CMD_JSON",
                     json.dumps(rot_cmd, separators=(",", ":"))))
    out.append(c_bytes("VEC_ROTATE_CMD_SIG64", rot_raw64))
    out.append("#define VEC_UNIX_20260927 %dull"
               % bake.parse_iso8601_utc("2026-09-27T00:00:00Z"))
    out.append("#define VEC_UNIX_2030 %dull" % baked_exp)

    with open(os.path.join(HERE, "vectors.h"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote vectors.h (%d json cases, canon %d bytes)"
          % (len(json_vec), len(canon)))


if __name__ == "__main__":
    main()
